  // -------------------------------------------------------------------------
  static boolean esPrimo( long num ) {
    boolean cond;
    if( num < 2 ) {
      cond = false;
    } else {
      cond = true;
      long i = 2;
      while( ( i < num )&&( cond ) ) {
        cond = ( num % i != 0 );
        i++;
      }
    }
    return( cond );
  }
